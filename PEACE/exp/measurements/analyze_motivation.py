        s_fifo = results_root / "reservation" / key / "fifo" / "summary.json"
        s_resv = results_root / "reservation" / key / "reservation" / "summary.json"
        if not s_fifo.exists() or not s_resv.exists():
            print(f"[warn] Missing Reservation summaries for {key}: {s_fifo} or {s_resv}")
            continue

        fifo = _read_json(s_fifo)
