#!/usr/bin/env python3
"""Analyze Motivation measurements for the PEACE IPDPS'26 paper.

The Motivation section contains several measurement-driven arguments:

1) Request-length distributions (handled by `plot_trace_distribution.py`).
2) FIFO head-of-line blocking: short queueing delay + throughput with vs without long requests.
3) Reservation underutilization: GPU idle rate + short queueing delay + throughput vs FIFO.
4) Priority starvation: long-request starvation rate.
5) Preemption pressure: total number of long-prefill preemptions (Table in the paper).

This script focuses on (2)–(5) by reading experiment outputs generated by
`run_workload_routed.py` and (optionally) `gpu_idle_monitor.py`.

All code and comments are English-only.
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

import matplotlib.pyplot as plt
import numpy as np


# Import paper model labels.
EXP_DIR = Path(__file__).resolve().parents[1]
import sys

sys.path.insert(0, str(EXP_DIR))
from peace_defaults import PAPER_MODELS  # type: ignore


PERCENTILES = [1, 25, 50, 75, 99]


def _read_json(path: Path) -> Dict[str, Any]:
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def _read_records_jsonl(path: Path) -> List[Dict[str, Any]]:
    out: List[Dict[str, Any]] = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            out.append(json.loads(line))
    return out


def _get_short_queue_delay_percentiles(summary: Dict[str, Any]) -> List[float]:
    q = summary.get("short_queue_delay_s") or {}
    vals: List[float] = []
    for p in PERCENTILES:
        vals.append(float(q.get(f"p{p}", float("nan"))))
    return vals


def _safe_div_list(xs: List[float], denom: float) -> List[float]:
    if denom is None or not np.isfinite(denom) or denom <= 0:
        return [float("nan") for _ in xs]
    return [float(x) / float(denom) if np.isfinite(x) else float("nan") for x in xs]


def _plot_boxpairs(
    labels: List[str],
    left_data: List[List[float]],
    right_data: List[List[float]],
    left_label: str,
    right_label: str,
    ylabel: str,
    out_path: Path,
) -> None:
    """Plot paired boxplots (paper style: each box uses 5 percentile points)."""
    fig, ax = plt.subplots(figsize=(8, 3.5))

    positions_left = np.arange(len(labels)) * 2.0
    positions_right = positions_left + 0.6
    mid = (positions_left + positions_right) / 2

    ax.boxplot(
        left_data,
        positions=positions_left,
        widths=0.5,
        patch_artist=True,
        whis=[0, 100],
        boxprops=dict(linewidth=1.3),
        medianprops=dict(color="black", linewidth=1.0),
        whiskerprops=dict(linewidth=1.3),
        capprops=dict(linewidth=1.3),
        flierprops=dict(marker="o", markersize=3, linestyle="none"),
    )
    ax.boxplot(
        right_data,
        positions=positions_right,
        widths=0.5,
        patch_artist=True,
        whis=[0, 100],
        boxprops=dict(linewidth=1.3),
        medianprops=dict(color="black", linewidth=1.0),
        whiskerprops=dict(linewidth=1.3),
        capprops=dict(linewidth=1.3),
        flierprops=dict(marker="o", markersize=3, linestyle="none"),
    )

    ax.set_xticks(mid)
    ax.set_xticklabels(labels, rotation=11)
    ax.set_ylim(0, 1.0)
    ax.set_ylabel(ylabel)

    # Simple legend using colored squares.
    legend_handles = [
        plt.Line2D([], [], marker="s", linestyle="None", label=left_label, markersize=12),
        plt.Line2D([], [], marker="s", linestyle="None", label=right_label, markersize=12),
    ]
    ax.legend(handles=legend_handles, loc="upper center", bbox_to_anchor=(0.5, 1.25), ncol=2, frameon=False)

    plt.tight_layout()
    out_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_path)
    plt.close(fig)


def _plot_throughput_bars(
    labels: List[str],
    left_vals: List[float],
    right_vals: List[float],
    left_label: str,
    right_label: str,
    out_path: Path,
) -> None:
    fig, ax = plt.subplots(figsize=(8, 3.5))
    positions_left = np.arange(len(labels)) * 2.0
    positions_right = positions_left + 0.6
    mid = (positions_left + positions_right) / 2

    ax.bar(positions_left, left_vals, width=0.5, edgecolor="black", label=left_label)
    ax.bar(positions_right, right_vals, width=0.5, edgecolor="black", label=right_label)

    ax.set_xticks(mid)
    ax.set_xticklabels(labels, rotation=11)
    ax.set_ylabel("Throughput (RPS)")

    ax.legend(loc="upper center", bbox_to_anchor=(0.5, 1.25), ncol=2, frameon=False)

    plt.tight_layout()
    out_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_path)
    plt.close(fig)


def _iter_paper_models(selected: Optional[List[str]]) -> List[Tuple[str, str]]:
    """Return [(model_key, display_name)] in paper order."""
    order = ["mistral7b", "phi3_14b", "yi34b", "llama31_70b"]
    keys = selected if selected else order
    out: List[Tuple[str, str]] = []
    for k in keys:
        if k not in PAPER_MODELS:
            raise SystemExit(f"Unknown model key: {k}. Valid: {sorted(PAPER_MODELS.keys())}")
        out.append((k, PAPER_MODELS[k].display_name))
    return out


def analyze_fifo(results_root: Path, out_dir: Path, models: Optional[List[str]]) -> None:
    """FIFO with vs without long requests (Motivation Fig q_delay_fifo + throughput_fifo)."""
    labels: List[str] = []
    data_wo: List[List[float]] = []
    data_w: List[List[float]] = []
    thr_wo: List[float] = []
    thr_w: List[float] = []

    for key, name in _iter_paper_models(models):
        s_wo = results_root / "fifo" / key / "without_long" / "summary.json"
        s_w = results_root / "fifo" / key / "with_long" / "summary.json"
        if not s_wo.exists() or not s_w.exists():
            print(f"[warn] Missing FIFO summaries for {key}: {s_wo} or {s_w}")
            continue

        wo = _read_json(s_wo)
        w = _read_json(s_w)

        q_wo = _get_short_queue_delay_percentiles(wo)
        q_w = _get_short_queue_delay_percentiles(w)
        denom = float(q_w[-1])  # normalize by p99 with long

        labels.append(name)
        data_wo.append(_safe_div_list(q_wo, denom))
        data_w.append(_safe_div_list(q_w, denom))
        thr_wo.append(float(wo.get("short_throughput_rps", float("nan"))))
        thr_w.append(float(w.get("short_throughput_rps", float("nan"))))

    if labels:
        _plot_boxpairs(
            labels=labels,
            left_data=data_wo,
            right_data=data_w,
            left_label="w/o long",
            right_label="w/ long",
            ylabel="Normalized\nqueueing delay",
            out_path=out_dir / "q_delay_fifo.pdf",
        )
        _plot_throughput_bars(
            labels=labels,
            left_vals=thr_wo,
            right_vals=thr_w,
            left_label="w/o long",
            right_label="w/ long",
            out_path=out_dir / "throughput_fifo.pdf",
        )
        print(f"Wrote: {out_dir / 'q_delay_fifo.pdf'}")
        print(f"Wrote: {out_dir / 'throughput_fifo.pdf'}")


def analyze_reservation(results_root: Path, out_dir: Path, models: Optional[List[str]]) -> None:
    """Reservation vs FIFO (Motivation Fig q_delay_resv + throughput_resv)."""
    labels: List[str] = []
    data_fifo: List[List[float]] = []
    data_resv: List[List[float]] = []
    thr_fifo: List[float] = []
